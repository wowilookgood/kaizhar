#!/usr/bin/env python3
"""Makes src/citra_switch/menu_font.h: the title picker's two font sizes as 8-bit coverage
atlases (Latin-1), from Inter (SIL Open Font License). Needs Pillow.

usage: gen-menu-font.py Inter-Regular.ttf Inter-Bold.ttf out.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

def atlas(path, size, name):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    width = 1024
    x = y = row = 0
    glyphs = []
    cells = []
    for code in range(32, 256):
        ch = chr(code)
        if 127 <= code < 160:
            glyphs.append((0, 0, 0, 0, 0, 0, 0))
            continue
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(right - left, 0), max(bottom - top, 0)
        if x + w + 1 > width:
            x, y, row = 0, y + row + 1, 0
        glyphs.append((x, y, w, h, left, top, round(font.getlength(ch))))
        cells.append((ch, x, y, left, top))
        x += w + 1
        row = max(row, h)
    height = y + row + 1
    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    for ch, gx, gy, left, top in cells:
        draw.text((gx - left, gy - top), ch, font=font, fill=255)
    data = image.tobytes()
    out = [f"// {name}: {size} px, line height {ascent + descent}, ascent {ascent}"]
    out.append(f"static const struct menu_glyph {name}_glyphs[224] = {{")
    for g in glyphs:
        out.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append(f"static const unsigned char {name}_pixels[{width} * {height}] = {{")
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};")
    out.append(f"static const struct menu_font {name} = {{{name}_glyphs, {name}_pixels, {width}, "
               f"{ascent + descent}, {ascent}}};")
    return "\n".join(out)

regular, bold, target = sys.argv[1:4]
parts = ["// Generated by hen/tools/gen-menu-font.py from Inter (SIL Open Font License 1.1,",
         "// https://rsms.me/inter/). Do not edit.",
         "#pragma once",
         "struct menu_glyph {",
         "    unsigned short x, y; // in the atlas",
         "    unsigned char w, h;",
         "    signed char left, top; // from the pen position and the line's top",
         "    unsigned char advance;",
         "};",
         "struct menu_font {",
         "    const struct menu_glyph* glyphs; // characters 32..255",
         "    const unsigned char* pixels;     // coverage, atlas_width per row",
         "    int atlas_width, line_height, ascent;",
         "};",
         atlas(regular, 30, "menu_font_text"),
         atlas(regular, 22, "menu_font_small"),
         atlas(bold, 44, "menu_font_heading")]
open(target, "w").write("\n".join(parts) + "\n")
